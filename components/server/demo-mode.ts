/**
 * โหมดเดโม — ไว้สาธิตหน้าห้องว่าตัวช่วยปรับตามระดับผู้เรียนจริง
 *
 * ปิดด้วย env ตัวเดียว: `DEMO_MODE=0` แล้วนักเรียนจะเปลี่ยนระดับตัวช่วยเองไม่ได้เลย
 * ตั้งใจไม่ใช้ชื่อขึ้นต้น NEXT_PUBLIC_ เพราะค่านั้นจะถูกฝังลงบันเดิลฝั่งเบราว์เซอร์
 * และนักเรียนแก้ค่าในหน้าเว็บได้ ค่านี้จึงอ่านได้เฉพาะฝั่งเซิร์ฟเวอร์
 */
export function isDemoMode(): boolean {
  return process.env.DEMO_MODE !== '0'
}
